DEFAULT = "Istanbul"


def fixed():
    out = []
    for m in range(-720, 841, 30):
        sign = "+" if m >= 0 else "-"
        a = abs(m)
        name = "UTC%s%02d:%02d" % (sign, a // 60, a % 60)
        tag = "%s%02d%02d" % (sign, a // 60, a % 60)
        # POSIX offset sign is inverted (positive = west of UTC)
        psign = "-" if m > 0 else ""
        poff = "%s%d" % (psign, a // 60) + (":%02d" % (a % 60) if a % 60 else "")
        out.append((name, "<%s>%s" % (tag, poff)))
    return out


def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    entries = NAMED + fixed()
    lines = [
        "// GENERATED by tools/gen_zones.py — do not edit by hand.",
        "// Named zones: POSIX TZ strings from IANA tzdata %s (posix_tz_db mapping). Then fixed offsets UTC-12:00…UTC+14:00." % TZDATA,
        '#include "core/Zones.h"',
        "",
        "namespace core {",
        "namespace Zones {",
        "",
        "static const Zone kZones[] = {",
    ]
    for n, p in entries:
        lines.append('    {"%s", "%s"},' % (esc(n), esc(p)))
    lines += [
        "};",
        "",
        "size_t count() { return sizeof(kZones) / sizeof(kZones[0]); }",
        "size_t namedCount() { return %d; }" % len(NAMED),
        "size_t defaultIndex() { return %d; }" % [n for n, _ in NAMED].index(DEFAULT),
        "const Zone& at(size_t i) { return kZones[i < count() ? i : defaultIndex()]; }",
        "const char* tzdataVersion() { return \"%s\"; }" % TZDATA,
        "",
        "} // namespace Zones",
        "} // namespace core",
        "",
    ]
    path = os.path.join(root, "src", "core", "ZonesTable.cpp")
    open(path, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
    print("wrote %s (%d named, %d total)" % (path, len(NAMED), len(entries)))


main()
