// core::Wav header parser (S5 data-model §2, FR-015).
#include <unity.h>
#include <cstring>
#include <vector>
#include "core/Wav.h"

using namespace core;

void setUp() {}
void tearDown() {}

namespace {

void put16(std::vector<uint8_t>& b, uint16_t v)
{
    b.push_back(uint8_t(v));
    b.push_back(uint8_t(v >> 8));
}
void put32(std::vector<uint8_t>& b, uint32_t v)
{
    for (int i = 0; i < 4; i++) b.push_back(uint8_t(v >> (8 * i)));
}
void tag(std::vector<uint8_t>& b, const char* t)
{
    for (int i = 0; i < 4; i++) b.push_back(uint8_t(t[i]));
}

struct Opt {
    uint16_t format = 1;
    uint16_t channels = 1;
    uint32_t rate = 16000;
    uint16_t bits = 16;
    uint32_t dataBytes = 1000;
    bool list = false;
    bool data = true;
    const char* wave = "WAVE";
    int riffAdjust = 0;   // added to the RIFF size
};

// A header only (the data bytes themselves are not included; the RIFF size declares them).
std::vector<uint8_t> make(const Opt& o)
{
    std::vector<uint8_t> b;
    tag(b, "RIFF");
    put32(b, 0);   // patched below
    tag(b, o.wave);
    tag(b, "fmt ");
    put32(b, 16);
    put16(b, o.format);
    put16(b, o.channels);
    put32(b, o.rate);
    put32(b, o.rate * o.channels * o.bits / 8);
    put16(b, uint16_t(o.channels * o.bits / 8));
    put16(b, o.bits);
    if (o.list) {
        tag(b, "LIST");
        put32(b, 26);
        for (int i = 0; i < 26; i++) b.push_back('x');
    }
    if (o.data) {
        tag(b, "data");
        put32(b, o.dataBytes);
    }
    const uint32_t riff = uint32_t(b.size() - 8 + (o.data ? o.dataBytes : 0)) + uint32_t(o.riffAdjust);
    for (int i = 0; i < 4; i++) b[4 + i] = uint8_t(riff >> (8 * i));
    return b;
}

} // namespace

static void test_minimal_valid()
{
    std::vector<uint8_t> b = make(Opt());
    Wav::Info w;
    TEST_ASSERT_TRUE(Wav::parse(b.data(), b.size(), w));
    TEST_ASSERT_EQUAL_UINT32(16000, w.rate);
    TEST_ASSERT_EQUAL_UINT16(1, w.channels);
    TEST_ASSERT_EQUAL_UINT16(16, w.bits);
    TEST_ASSERT_EQUAL_UINT32(44, w.dataOffset);
    TEST_ASSERT_EQUAL_UINT32(1000, w.dataBytes);
    TEST_ASSERT_EQUAL_UINT32(31, Wav::durationMs(w));   // 500 samples at 16 kHz
}

static void test_list_chunk_skipped()
{
    Opt o;
    o.list = true;
    std::vector<uint8_t> b = make(o);
    Wav::Info w;
    TEST_ASSERT_TRUE(Wav::parse(b.data(), b.size(), w));
    TEST_ASSERT_EQUAL_UINT32(44 + 8 + 26, w.dataOffset);
}

static void test_rejects()
{
    Wav::Info w;
    Opt o;
    o.channels = 2;
    std::vector<uint8_t> b = make(o);
    TEST_ASSERT_FALSE(Wav::parse(b.data(), b.size(), w));   // stereo
    o = Opt();
    o.bits = 8;
    b = make(o);
    TEST_ASSERT_FALSE(Wav::parse(b.data(), b.size(), w));   // 8-bit
    o = Opt();
    o.format = 3;
    o.bits = 32;
    b = make(o);
    TEST_ASSERT_FALSE(Wav::parse(b.data(), b.size(), w));   // IEEE float
    o = Opt();
    o.rate = 4000;
    b = make(o);
    TEST_ASSERT_FALSE(Wav::parse(b.data(), b.size(), w));
    o.rate = 96000;
    b = make(o);
    TEST_ASSERT_FALSE(Wav::parse(b.data(), b.size(), w));
    o = Opt();
    o.data = false;
    b = make(o);
    TEST_ASSERT_FALSE(Wav::parse(b.data(), b.size(), w));   // no data chunk
    b = make(Opt());
    TEST_ASSERT_FALSE(Wav::parse(b.data(), 30, w));         // truncated
    TEST_ASSERT_FALSE(Wav::parse(b.data(), 0, w));
    TEST_ASSERT_FALSE(Wav::parse(nullptr, 44, w));
    o = Opt();
    o.wave = "AVI ";
    b = make(o);
    TEST_ASSERT_FALSE(Wav::parse(b.data(), b.size(), w));   // RIFF but not WAVE
    o = Opt();
    o.riffAdjust = -100;
    b = make(o);
    TEST_ASSERT_FALSE(Wav::parse(b.data(), b.size(), w));   // data beyond the declared file size
}

// The first 44 bytes of data/audio/chime.wav as generated by tools/gen_audio.py.
static void test_real_chime_header()
{
    const uint8_t h[44] = {0x52, 0x49, 0x46, 0x46, 0x64, 0x83, 0x00, 0x00, 0x57, 0x41, 0x56, 0x45, 0x66, 0x6D, 0x74,
                           0x20, 0x10, 0x00, 0x00, 0x00, 0x01, 0x00, 0x01, 0x00, 0x80, 0x3E, 0x00, 0x00, 0x00, 0x7D,
                           0x00, 0x00, 0x02, 0x00, 0x10, 0x00, 0x64, 0x61, 0x74, 0x61, 0x40, 0x83, 0x00, 0x00};
    Wav::Info w;
    TEST_ASSERT_TRUE(Wav::parse(h, sizeof(h), w));
    TEST_ASSERT_EQUAL_UINT32(16000, w.rate);
    TEST_ASSERT_EQUAL_UINT32(44, w.dataOffset);
    TEST_ASSERT_EQUAL_UINT32(0x8340, w.dataBytes);   // 16800 samples
    TEST_ASSERT_EQUAL_UINT32(1050, Wav::durationMs(w));
}

int main()
{
    UNITY_BEGIN();
    RUN_TEST(test_minimal_valid);
    RUN_TEST(test_list_chunk_skipped);
    RUN_TEST(test_rejects);
    RUN_TEST(test_real_chime_header);
    return UNITY_END();
}
